def render_issue(issue: dict) -> str:
    out = [
        "<li>",
        f'<p class="kicker">Issue {issue["number"]} · {long_date(issue["date"])}</p>',
        f'<h3><a href="{esc(issue["linkedin"])}">{esc_text(issue["title"])}</a></h3>',
        f'<p>{esc_text(issue["finding"])}</p>',
    ]
    if issue.get("commands"):
        lines = "\n".join(esc_text(line) for line in issue["commands"])
        out.append(f"<pre><code>{lines}</code></pre>")
    ways = [f'<li><a href="{esc(issue["linkedin"])}">Read the issue</a></li>']
    if "post" in issue:
        ways.append(f'<li><a href="{esc(issue["post"])}">The long version</a></li>')
    if "repository" in issue:
        ways.append(f'<li><a href="{esc(issue["repository"])}">'
                    f'{esc_text(issue["package"])} on GitHub</a></li>')
    if "browser" in issue:
        ways.append(f'<li><a href="{esc(issue["browser"])}">Try it in the browser</a></li>')
    out += ['<ul class="ways">', *ways, "</ul>", "</li>"]
    return "\n".join(out)


def render_page(issues: list[dict]) -> str:
    items = "\n".join(render_issue(issue) for issue in issues)
    return f'{HEAD}\n<ol class="issues" reversed>\n{items}\n</ol>\n{TAIL}'


def render_readme(readme: str, issues: list[dict]) -> str:
    def cell(text: str) -> str:
        return text.replace("|", "\\|")

    rows = ["| # | Date | Issue | Package | Long version |",
            "|---|---|---|---|---|"]
    for issue in issues:
        package = (f'[{cell(issue["package"])}]({issue["repository"]})'
                   if "repository" in issue else "")
        post = f'[on my site]({issue["post"]})' if "post" in issue else ""
        rows.append(f'| {issue["number"]} | {short_date(issue["date"])} | '
                    f'[{cell(issue["title"])}]({issue["linkedin"]}) | {package} | {post} |')
    block = "\n".join([README_START, "", *rows, "", README_END])
    pattern = re.compile(re.escape(README_START) + r".*?" + re.escape(README_END), re.S)
    if not pattern.search(readme):
        raise SystemExit("README.md has no issues block to fill")
    return pattern.sub(lambda _: block, readme, count=1)


