# Where a link on the page may point. Anything the page loads (stylesheet,
# icon) must be relative, so it comes from the same place as the page.
LINK_HOSTS = ("https://mohammadi.cv/", "https://github.com/mohammadi-hadi/",
              "https://www.linkedin.com/")
# <link> tags a browser does not fetch while showing the page.
NOT_FETCHED = {"canonical", "alternate", "author", "license"}

README_START = "<!-- issues start: generated by build.py from issues.json -->"
README_END = "<!-- issues end -->"


def esc(text: str) -> str:
    return html.escape(text, quote=True)


def esc_text(text: str) -> str:
    """For text between tags, where quotes and apostrophes can stay as they are."""
    return html.escape(text, quote=False)


def long_date(iso: str) -> str:
    d = date.fromisoformat(iso)
    return f"{d.day} {MONTHS[d.month - 1]} {d.year}"


def short_date(iso: str) -> str:
    d = date.fromisoformat(iso)
    return f"{d.day} {MONTHS[d.month - 1][:3]} {d.year}"


