#!/usr/bin/env python3
"""Build the index of Weekend Learning from issues.json.

    python3 build.py                  # write index.html and the README table
    python3 build.py --check          # change nothing, fail if either is stale
    python3 build.py --source DIR     # the newsletter's working folder

index.html and the table in README.md are generated; issues.json is the only
thing to edit. Adding an issue is one entry there.

When the newsletter's working folder is reachable, every entry is also
checked against it:

- the number, date, title and LinkedIn link against the Published table in
  CALENDAR.md, and the title against the TITLE line of the issue file;
- the finding, word for word, against the text of the issue;
- each command, as a whole line, against the code blocks of the issue;
- the repository, post and browser links against the links in the issue.

An issue that is not in the Published table cannot be listed, and a
published issue that is missing here fails the check too. The working folder
is private; without it (a fresh clone) those checks are skipped and the rest
still run. It is found at --source, else $WL_SOURCE, else the folder
Weekend-Learning next to this repository.

Standard library only. The output depends on issues.json alone, so running
the build twice changes nothing.
"""
