def load_issues(path: Path) -> list[dict]:
    issues = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(issues, list) or not issues:
        raise SystemExit("issues.json must be a non-empty list")
    problems = []
    for i, issue in enumerate(issues):
        where = f"issues.json entry {i + 1}"
        for key, kind in REQUIRED.items():
            if not isinstance(issue.get(key), kind):
                problems.append(f"{where}: '{key}' is missing or not a {kind.__name__}")
        for key, kind in OPTIONAL.items():
            if key in issue and not isinstance(issue[key], kind):
                problems.append(f"{where}: '{key}' is not a {kind.__name__}")
        for key in set(issue) - set(REQUIRED) - set(OPTIONAL):
            problems.append(f"{where}: unknown field '{key}'")
        for key, prefix in PREFIX.items():
            if key in issue and not str(issue[key]).startswith(prefix):
                problems.append(f"{where}: '{key}' should start with {prefix}")
        if "repository" in issue and "package" not in issue:
            problems.append(f"{where}: a repository needs its package name")
        for line in issue.get("commands", []):
            if not isinstance(line, str) or not line.strip() or "\n" in line:
                problems.append(f"{where}: each command is one non-empty line")
        try:
            date.fromisoformat(str(issue.get("date")))
        except ValueError:
            problems.append(f"{where}: date should be YYYY-MM-DD")
    numbers = [issue.get("number") for issue in issues]
    if len(set(numbers)) != len(numbers):
        problems.append("issues.json: an issue number appears twice")
    if problems:
        raise SystemExit("\n".join(problems))
    return sorted(issues, key=lambda issue: issue["number"], reverse=True)


