class Links(HTMLParser):
    """Collects href and src values, and the text of every <pre>."""

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.anchors: list[str] = []
        self.loads: list[str] = []
        self.pre: list[str] = []
        self._in_pre = 0

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == "a" and attrs.get("href"):
            self.anchors.append(attrs["href"])
        elif tag == "link" and (attrs.get("rel") or "").lower() in NOT_FETCHED:
            self.anchors.append(attrs.get("href") or "")
        elif tag in ("link", "script", "img", "iframe", "source", "video", "audio"):
            for key in ("href", "src"):
                if attrs.get(key):
                    self.loads.append(attrs[key])
        if tag == "pre":
            self._in_pre += 1
            self.pre.append("")

    def handle_endtag(self, tag):
        if tag == "pre" and self._in_pre:
            self._in_pre -= 1

    def handle_data(self, data):
        if self._in_pre:
            self.pre[-1] += data


def parse(markup: str) -> Links:
    p = Links()
    p.feed(markup)
    p.close()
    return p


def check_page(page: str) -> list[str]:
    """The page loads nothing from another host and links only where it should."""
    problems = []
    found = parse(page)
    for ref in found.loads:
        if re.match(r"^[a-z][a-z0-9+.-]*:|^//", ref, re.I):
            problems.append(f"index.html loads {ref} from another place")
        elif not (REPO / ref).exists():
            problems.append(f"index.html loads {ref}, which is not in the repository")
    for ref in found.anchors:
        if not ref.startswith(LINK_HOSTS):
            problems.append(f"index.html links {ref}")
    css = (REPO / "assets" / "style.css").read_text(encoding="utf-8")
    for url in re.findall(r"url\(([^)]*)\)|@import\s+([^;]+)", css):
        problems.append(f"style.css loads {url}")
    return problems


def issue_text(markup: str) -> str:
    """The issue as a reader sees it: tags gone, entities decoded, spaces collapsed."""
    markup = re.sub(r"(?s)<!--.*?-->|<script.*?</script>|<style.*?</style>", " ", markup)
    return " ".join(html.unescape(re.sub(r"<[^>]+>", " ", markup)).split())


def squash(text: str) -> str:
    return " ".join(text.split())


def published_table(calendar: str) -> dict[int, dict]:
    section = calendar.split("## Published", 1)[1].split("\n## ", 1)[0]
    rows = {}
    for number, day, title, url in re.findall(
            r"^\|\s*(\d+)\s*\|\s*([^|]+?)\s*\|\s*\[(.+)\]\((\S+)\)\s*\|\s*$", section, re.M):
        rows[int(number)] = {"date": day, "title": title, "linkedin": url}
    return rows


def check_against_workspace(issues: list[dict], source: Path) -> tuple[list[str], list[str]]:
    problems, notes = [], []
    published = published_table((source / "CALENDAR.md").read_text(encoding="utf-8"))
    listed = {issue["number"] for issue in issues}
    for number in sorted(set(published) - listed):
        problems.append(f"issue {number} is in the Published table but not in issues.json")
    for issue in sorted(issues, key=lambda issue: issue["number"]):
        n = issue["number"]
        row = published.get(n)
        if row is None:
            problems.append(f"issue {n} is not in the Published table of CALENDAR.md")
            continue
        if short_date(issue["date"]) != row["date"]:
            problems.append(f"issue {n}: date {issue['date']} but the calendar says {row['date']}")
        if issue["title"] != row["title"]:
            problems.append(f"issue {n}: title differs from the calendar: {row['title']!r}")
        if issue["linkedin"] != row["linkedin"]:
            problems.append(f"issue {n}: LinkedIn link differs from the calendar: {row['linkedin']}")

        path = source / issue["source"]
        if not path.exists():
            problems.append(f"issue {n}: {issue['source']} not found")
            continue
        markup = path.read_text(encoding="utf-8")
        m = re.search(r"TITLE:\s*(.+)", markup)
        if not m or m.group(1).strip() != issue["title"]:
            problems.append(f"issue {n}: title differs from the TITLE line of {issue['source']}")
        if squash(issue["finding"]) not in issue_text(markup):
            problems.append(f"issue {n}: the finding is not word for word in {issue['source']}")
        found = parse(markup)
        lines = {line.strip() for block in found.pre for line in block.splitlines()}
        for line in issue.get("commands", []):
            if line not in lines:
                problems.append(f"issue {n}: command not in the issue's code blocks: {line}")
        for key in ("repository", "post", "browser"):
            if key in issue and issue[key] not in found.anchors:
                problems.append(f"issue {n}: {key} {issue[key]} is not linked from the issue")
        checked = 5 + len(issue.get("commands", [])) + sum(
            key in issue for key in ("repository", "post", "browser"))
        notes.append(f"issue {n}: {checked} fields match {issue['source']} and the calendar")
    return problems, notes


# --------------------------------------------------------------------------

def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="change nothing; fail if index.html or README.md is out of date")
    ap.add_argument("--source", type=Path, help="the newsletter's working folder")
    args = ap.parse_args()

    issues = load_issues(REPO / "issues.json")
    targets = {
        REPO / "index.html": render_page(issues),
        REPO / "README.md": render_readme(
            (REPO / "README.md").read_text(encoding="utf-8"), issues),
    }

    problems = []
    for path, text in targets.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            print(f"{path.name} up to date")
        elif args.check:
            problems.append(f"{path.name} is out of date; run python3 build.py")
        else:
            path.write_text(text, encoding="utf-8")
            print(f"{path.name} written")

    problems += check_page(targets[REPO / "index.html"])

    source = args.source or Path(os.environ.get("WL_SOURCE", REPO.parent / "Weekend-Learning"))
    if (source / "CALENDAR.md").exists():
        found, notes = check_against_workspace(issues, source)
        problems += found
        for note in notes:
            print(note)
    else:
        print(f"newsletter folder not found at {source}; checks against it skipped")

    print(f"{len(issues)} issues listed, newest {max(i['number'] for i in issues)}")
    for problem in problems:
        print(f"FAIL {problem}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
